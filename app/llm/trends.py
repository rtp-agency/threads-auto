"""LLM-фильтр новостных заголовков (дешёвая модель каскада, ТЗ п.4).

Из сырых заголовков отбирает те, что годятся под формат
"личная история клиента (ниша задаётся в BASE_SYSTEM) + актуальное событие".
Фильтр строгий: большинство заголовков отсеивается.
"""
from app.config import settings
from app.llm.providers import structured_completion

FILTER_SYSTEM = """\
Ти — суворий редактор контенту для Threads-акаунта клієнта (див. BASE_SYSTEM).
Його топ-формат — особиста історія/провокація, що чіпляється за МАСОВУ, емоційну,
всім відому подію, із питанням до аудиторії наприкінці (референс: пост про бій
приклад вірусного тренд-поста клієнта).

Його тренд-пости — це реакція на ВІРУСНУ ЕМОЦІЙНУ ПОДІЮ, про яку зараз усі
говорять і сперечаються, через призму особистої історії автора і його аудиторії.
Формат — легка іронічна провокація з питанням до аудиторії.

Тобі дадуть список новинних заголовків. За замовчуванням ВІДХИЛЯЙ. Пропускай
заголовок ТІЛЬКИ якщо виконуються ВСІ умови:
1) це ВІРУСНИЙ ІНФОПРИВІД — гучна подія-момент, яку зараз обговорюють маси і на
   яку в людей є емоція/думка (спортивна драма, скандал, гучний вчинок зірки,
   вірусний випадок, культурний феномен). Те, про що сперечаються в коментах;
2) тема ЛЕГКА — доречно пожартувати, вийде іронія, а не співчуття;
3) з події можна зробити ПРОВОКАЦІЮ або особисту історію про аудиторію/нішу —
   а не словниковий урок.

⛔ КЛЮЧОВЕ ПРАВИЛО: якщо єдиний звʼязок із нішею клієнта — це «вивчимо лексику/слова
про цю тему» (машини, меблі, техніку тощо), то це ШТУЧНИЙ місток — ВІДХИЛЯЙ.
Пост має чіплятися за ЕМОЦІЮ і драму події, а не за словниковий запас.

⛔ ЗАВЖДИ відхиляй, навіть якщо згадана бренд чи країна з ніші клієнта:
- анонси й запуски продуктів, релізи, презентації, новинки, рейтинги, «топ-N»,
  огляди товарів (напр. «IKEA випустила меблі», «Volkswagen дебютував кросовер»,
  «найпопулярніші авто») — це не вірусна подія, а реклама/продуктова новина;
- усе трагічне: війна, обстріли, атаки, загиблі, поранені, теракти, катастрофи,
  ДТП зі смертями, вбивства, насильство, хвороби, смерті, стихійні лиха;
- рутинну і партійну політику, закони, засідання, призначення, зброю, курси
  валют, економічні звіти, прес-релізи, погоду, технічні/вузькі новини, статистику.

Приклад ХОРОШОЇ теми: гучний бій/матч, скандал зірки, вірусний вчинок, феномен,
який усі обговорюють. Приклад ПОГАНОЇ: «IKEA випустила портативні меблі»,
«дебютував електрокросовер», «рейтинг дизельних авто», прийняли закон.

Для кожного відібраного заголовка постав relevance_score від 0 до 1. Став 0.7+
лише коли впевнений, що це справді вірусний інфопривід і вийде класна провокація.
У полі angle одним реченням опиши САМЕ провокацію/особисту історію (не «вивчити
слова»); якщо виходить лише словниковий урок — відхиляй."""

FILTER_SCHEMA = {
    "type": "object",
    "properties": {
        "selected": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "index": {"type": "integer"},
                    "relevance_score": {"type": "number"},
                    "angle": {"type": "string"},
                },
                "required": ["index", "relevance_score", "angle"],
                "additionalProperties": False,
            },
        }
    },
    "required": ["selected"],
    "additionalProperties": False,
}


# Порог релевантности: темы слабее этого не сохраняем (лучше пусто, чем мусор).
MIN_RELEVANCE = 0.7

# Детерминированный стоп-список: заголовки с этими подстроками отсекаются ДО LLM,
# чтобы война/трагедии физически не могли пройти, что бы ни решила модель.
# Подстроки в нижнем регистре, ловят и укр., и рус. написание.
WAR_TRAGEDY_TERMS = (
    "ракет", "дрон", "бпла", "обстріл", "обстрел", "атак", "удар", "вибух",
    "взрыв", "загин", "погиб", "поранен", "ранен", "вбив", "убий", "убит",
    "теракт", "катастроф", "жертв", "полон", "окупац", "оккупац", "фронт",
    "війн", "войн", "снаряд", "танкер", "боєприпас", "боеприпас", "іскандер",
    "искандер", "шахед", "балістик", "балистик", "розстріл", "расстрел",
    "смерт", "помер", "загибел", "погибел", "потонул", "трагед", "мертв",
    "зброя", "оружие", "наступ", "бої", "бой ", "евакуац", "эвакуац", "поховал",
    "похорон", "згорів", "сгорел", "пожеж", "пожар", "ЗСУ", "всу ", "полегл",
)


def _is_grim(headline: str) -> bool:
    h = headline.lower()
    return any(term in h for term in WAR_TRAGEDY_TERMS)


def filter_headlines(headlines: list[str], max_selected: int = 3) -> list[dict]:
    """Возвращает [{index, relevance_score, angle}] — отобранные заголовки.

    index — позиция в исходном списке headlines.
    """
    if not headlines:
        return []

    # 1) детерминированный отсев войны/трагедий до LLM
    candidates = [(i, h) for i, h in enumerate(headlines) if not _is_grim(h)]
    if not candidates:
        return []

    # 2) умный отсев (вирусное событие vs продуктовая новость) — моделью посильнее
    numbered = "\n".join(f"{j}. {h}" for j, (_, h) in enumerate(candidates))
    data = structured_completion(
        model=settings.classifier_model,
        system_blocks=[FILTER_SYSTEM],
        user_text=f"Заголовки:\n{numbered}",
        schema=FILTER_SCHEMA,
        max_tokens=6000,
        reasoning_effort="medium",
    )

    out = []
    for s in data["selected"]:
        j = s.get("index")
        if j is None or not (0 <= j < len(candidates)):
            continue
        if s.get("relevance_score", 0) < MIN_RELEVANCE:
            continue
        orig_i = candidates[j][0]
        out.append(
            {
                "index": orig_i,
                "relevance_score": s["relevance_score"],
                "angle": s.get("angle", ""),
            }
        )
    out.sort(key=lambda s: s["relevance_score"], reverse=True)
    return out[:max_selected]
