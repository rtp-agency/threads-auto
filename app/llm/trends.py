"""LLM-фильтр новостных заголовков (дешёвая модель каскада, ТЗ п.4).

Из сырых заголовков отбирает те, что годятся под формат
"личная история клиента (ниша задаётся в BASE_SYSTEM) + актуальное событие".
Фильтр строгий: большинство заголовков отсеивается.
"""
from app.config import settings
from app.llm.providers import structured_completion

FILTER_SYSTEM = """\
Ти — редактор контенту для Threads-акаунта клієнта (див. BASE_SYSTEM). Його
тренд-пости — це реакція на ВІРУСНУ, ЕМОЦІЙНУ, всім відому подію через призму
особистої історії/провокації з питанням до аудиторії наприкінці.

🎯 ПОТРІБНЕ РІЗНОМАНІТТЯ ТЕМ. НЕ обмежуйся однією сферою (напр. спортом).
Пропускай будь-яку ГУЧНУ, ДИСКУСІЙНУ подію з різних сфер:
- гучні політичні скандали, абсурд, меми і драми з політики (НЕ рутина — саме
  те, що вибухнуло і всі обговорюють/сміються/сперечаються);
- вірусні інтернет-події, меми, тренди, челенджі, дивні відео, феномени мережі;
- абсурдні/кумедні новини, життєві скандали, суспільні суперечки, гучні витівки;
- спорт — ТІЛЬКИ якщо це справді велика подія-момент, і НЕ роби всі теми про спорт;
- культурні феномени, гучні висловлювання, суспільні тренди.

Умови відбору (всі три):
1) ВІРУСНИЙ ІНФОПРИВІД — про це зараз говорять/сперечаються маси, є емоція;
2) тема ЛЕГКА/дискусійна — можна пожартувати чи спровокувати, а не співчувати;
3) з події виходить ПРОВОКАЦІЯ або особиста історія (а не «вивчимо слова»).

⛔ ВІДХИЛЯЙ:
- нудні газетні/офіційні новини, прес-релізи, рутинну політику (засідання,
  призначення, закони «прийняли/розглянули»), курси валют, звіти, погоду,
  статистику, вузькі технічні новини;
- банальні новини про селебриті рівня «зірка вийшла у світ / купила будинок /
  показала фото» — БЕЗ вірусної драми чи скандалу (просто світська хроніка);
- анонси/запуски продуктів, релізи, презентації, рейтинги, огляди товарів;
- усе трагічне: війна, обстріли, атаки, загиблі, теракти, катастрофи, ДТП зі
  смертями, вбивства, насильство, хвороби, смерті, стихійні лиха.

⛔ КЛЮЧОВЕ ПРАВИЛО: якщо єдиний звʼязок із нішею — «вивчимо лексику про цю тему»,
це ШТУЧНИЙ місток — ВІДХИЛЯЙ. Пост чіпляється за ЕМОЦІЮ/драму, не за слова.

Для кожного відібраного заголовка постав relevance_score 0-1 (0.7+ лише коли це
справді вірусний привід). У полі angle одним реченням опиши САМЕ провокацію/
особисту історію."""

FILTER_SCHEMA = {
    "type": "object",
    "properties": {
        "selected": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "index": {"type": "integer"},
                    "relevance_score": {"type": "number"},
                    "angle": {"type": "string"},
                },
                "required": ["index", "relevance_score", "angle"],
                "additionalProperties": False,
            },
        }
    },
    "required": ["selected"],
    "additionalProperties": False,
}


# Порог релевантности: темы слабее этого не сохраняем (лучше пусто, чем мусор).
MIN_RELEVANCE = 0.7

# Детерминированный стоп-список: заголовки с этими подстроками отсекаются ДО LLM,
# чтобы война/трагедии физически не могли пройти, что бы ни решила модель.
# Подстроки в нижнем регистре, ловят и укр., и рус. написание.
WAR_TRAGEDY_TERMS = (
    "ракет", "дрон", "бпла", "обстріл", "обстрел", "атак", "удар", "вибух",
    "взрыв", "загин", "погиб", "поранен", "ранен", "вбив", "убий", "убит",
    "теракт", "катастроф", "жертв", "полон", "окупац", "оккупац", "фронт",
    "війн", "войн", "снаряд", "танкер", "боєприпас", "боеприпас", "іскандер",
    "искандер", "шахед", "балістик", "балистик", "розстріл", "расстрел",
    "смерт", "помер", "загибел", "погибел", "потонул", "трагед", "мертв",
    "зброя", "оружие", "наступ", "бої", "бой ", "евакуац", "эвакуац", "поховал",
    "похорон", "згорів", "сгорел", "пожеж", "пожар", "ЗСУ", "всу ", "полегл",
)


def _is_grim(headline: str) -> bool:
    h = headline.lower()
    return any(term in h for term in WAR_TRAGEDY_TERMS)


def filter_headlines(headlines: list[str], max_selected: int = 3) -> list[dict]:
    """Возвращает [{index, relevance_score, angle}] — отобранные заголовки.

    index — позиция в исходном списке headlines.
    """
    if not headlines:
        return []

    # 1) детерминированный отсев войны/трагедий до LLM
    candidates = [(i, h) for i, h in enumerate(headlines) if not _is_grim(h)]
    if not candidates:
        return []

    # 2) умный отсев (вирусное событие vs продуктовая новость) — моделью посильнее
    numbered = "\n".join(f"{j}. {h}" for j, (_, h) in enumerate(candidates))
    data = structured_completion(
        model=settings.classifier_model,
        system_blocks=[FILTER_SYSTEM],
        user_text=f"Заголовки:\n{numbered}",
        schema=FILTER_SCHEMA,
        max_tokens=6000,
        reasoning_effort="medium",
    )

    out = []
    for s in data["selected"]:
        j = s.get("index")
        if j is None or not (0 <= j < len(candidates)):
            continue
        if s.get("relevance_score", 0) < MIN_RELEVANCE:
            continue
        orig_i = candidates[j][0]
        out.append(
            {
                "index": orig_i,
                "relevance_score": s["relevance_score"],
                "angle": s.get("angle", ""),
            }
        )
    out.sort(key=lambda s: s["relevance_score"], reverse=True)
    return out[:max_selected]
